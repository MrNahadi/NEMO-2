// Generates src/styles/graphite-tokens.css from the Graphite design system's tokens.json.
// Graphite stays the single source of truth; NEMO's spacing and size changes live in nemo.css.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../design-system/graphite/project/tokens.json");
const target = resolve(here, "../src/styles/graphite-tokens.css");
const tokens = JSON.parse(readFileSync(source, "utf8"));

const colorTokens = tokens.color.tokens;
const byName = new Map(colorTokens.map((t) => [t.name, t.value]));

function resolveColor(value, theme, seen = new Set()) {
  const raw = typeof value === "string" ? value : value[theme];
  const ref = /^\{(.+)\}$/.exec(raw);
  if (!ref) return raw;
  const name = ref[1];
  if (seen.has(name)) throw new Error(`Circular colour reference: ${name}`);
  seen.add(name);
  if (!byName.has(name)) throw new Error(`Unknown colour reference: ${name}`);
  return resolveColor(byName.get(name), theme, seen);
}

const lines = (theme) =>
  colorTokens.map((t) => `  --${t.name}: ${resolveColor(t.value, theme)};`).join("\n");

const simple = (group) =>
  (tokens[group]?.tokens ?? [])
    .filter((t) => typeof t.value === "string")
    .map((t) => `  --${t.name}: ${t.value};`)
    .join("\n");

const shadows = (theme) =>
  tokens.shadow.tokens.map((t) => `  --${t.name}: ${typeof t.value === "string" ? t.value : t.value[theme]};`).join("\n");

const families = tokens.type.families;
const css = `/* Generated by scripts/build-tokens.mjs from design-system/graphite/project/tokens.json. Do not edit. */
:root {
${lines("light")}
${shadows("light")}
${simple("radius")}
${simple("duration")}
${simple("easing")}
${simple("tracking")}
${simple("weight")}
  --font-sans: ${families.sans};
  color-scheme: light;
}

[data-theme="dark"] {
${lines("dark")}
${shadows("dark")}
  color-scheme: dark;
}
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, css);
console.log(`Wrote ${target} (${colorTokens.length} colours)`);
