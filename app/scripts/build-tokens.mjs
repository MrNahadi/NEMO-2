// Generates src/styles/tokens.css from design-system/nemo/tokens.json (NEMO on Vercel Geist).
// The JSON is the single source of truth; never hand-edit the generated CSS.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../design-system/nemo/tokens.json");
const target = resolve(here, "../src/styles/tokens.css");
const tokens = JSON.parse(readFileSync(source, "utf8"));

const themed = (group, theme) =>
  Object.entries(tokens[group]).map(([name, v]) => `  --${group === "shadow" ? "shadow-" : ""}${name}: ${typeof v === "string" ? v : v[theme]};`);
const plain = (group) => Object.entries(tokens[group]).map(([name, v]) => `  --${name}: ${v};`);

const css = `/* Generated by scripts/build-tokens.mjs from design-system/nemo/tokens.json. Do not edit. */
:root {
${[...themed("color", "light"), ...themed("shadow", "light"), ...["space", "radius", "font", "size", "motion"].flatMap(plain)].join("\n")}
  color-scheme: light;
}

[data-theme="dark"] {
${[...themed("color", "dark"), ...themed("shadow", "dark")].join("\n")}
  color-scheme: dark;
}
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, css);
console.log(`Wrote ${target} (${Object.keys(tokens.color).length} colours)`);
