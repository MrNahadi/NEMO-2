"""Write data/facts.md: every number from the report data runs, in readable form."""

from __future__ import annotations

import json
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"


def fmt(v, d=3):
    if isinstance(v, float):
        return f"{v:.{d}g}" if abs(v) < 1e-3 or abs(v) >= 1e5 else f"{v:.{d}f}".rstrip("0").rstrip(".")
    return str(v)


def main() -> None:
    lines: list[str] = ["# Report data (generated by tools/dump_facts.py)", ""]
    cases = json.loads((DATA / "cases.json").read_text())
    for part, info in cases.items():
        run = DATA / info["run_dir"]
        res = json.loads((run / "results.json").read_text())
        lines += [f"## Case: {part} ({info['name']})", "", f"Run time {info['seconds']:.1f} s. Search: {res['search']}.", ""]
        lines.append("Job: " + json.dumps(res["job"]))
        lines.append("")
        lines.append("Loads: " + json.dumps({k: (round(v, 3) if isinstance(v, float) else v) for k, v in res["loads"].items()}))
        lines.append("")
        lines.append("Load steps:")
        for s in res.get("load_steps", []):
            lines.append(f"- {s['label']}: {s['formula']} ; {s['substituted']} = {s['result']}")
        lines.append("")
        for d in res["designs"]:
            r = d["check_report"]
            lines.append(f"### Design {d['key']} ({d['label']}), mass {r['mass_kg']:.3f} kg, passed {r['passed']}, governing {r['governing']}")
            lines.append("Design: " + json.dumps(r["design"]))
            for extra in ("shackle", "pipe", "ubolt", "span", "masses_kg", "ribs", "rib_pitch_mm", "stock_material"):
                if extra in r:
                    val = r[extra]
                    if extra == "span":
                        val = {k: v for k, v in val.items() if k != "steps"}
                    lines.append(f"{extra}: {json.dumps(val)}")
            lines.append("")
            lines.append("| check | category | severity | demand | capacity | unit | use % | source |")
            lines.append("|---|---|---|---|---|---|---|---|")
            for c in r["checks"]:
                lines.append(f"| {c['title']} ({c['id']}) | {c['category']} | {c['severity']} | {fmt(c['demand'])} | {fmt(c['capacity'])} | {c['unit']} | {c['utilization']*100:.1f} | {c['source']} |")
            lines.append("")
            f = d.get("fea")
            if f:
                lines.append(f"FEA: peak {f['head_von_mises_mpa']:.2f} MPa, yield {f['yield_strength_mpa']:.0f}, FoS {f['factor_of_safety_on_yield']:.2f}, "
                             f"convergence change {f['convergence_change']*100:.3f}%, converged {f['converged']}, region {f.get('region', 'head (hole region)')}, "
                             f"hand {f.get('hand_stress_mpa')} ({f.get('hand_label', '')})")
                for lvl in f["levels"]:
                    lines.append(f"- level {lvl['level']}: size {lvl['global_size_mm']:.2f}/{lvl['local_size_mm']:.2f} mm, {lvl['elements']} elements, "
                                 f"{lvl['dofs']} dofs, peak {lvl['head_von_mises_mpa']:.2f} MPa, max {lvl['max_von_mises_mpa']:.1f} MPa, "
                                 f"disp {lvl['max_displacement_mm']:.4f} mm, balance {lvl['reaction_balance_error']:.1e}, solve {lvl['solve_seconds']:.1f} s, "
                                 f"applied {[round(v, 1) for v in lvl['applied_force_n']]}")
            lines.append(f"CAD volume {d['cad_volume_mm3']:.1f} mm3")
            lines.append("")
        events = json.loads((run / "engineering-log.json").read_text())
        cads = [e for e in events if e["kind"] == "cad"]
        lines.append("CAD vs formula: " + ", ".join(f"{e['target']} {e['difference']*100:.4f}%" for e in cads))
        lines.append("")
    v = json.loads((DATA / "verification.json").read_text())
    lines += ["## Verification", "", f"All passed: {v['passed']}, total {v['seconds_total']:.1f} s", ""]
    for b in v["benchmarks"]:
        lines.append(f"### {b['title']} ({b['id']}), source: {b['source']}, {b['seconds']:.1f} s, mesh {b.get('mesh')}")
        for c in b["comparisons"]:
            lines.append(f"- {c['quantity']}: reference {fmt(c['reference'], 6)}, NEMO {fmt(c['nemo'], 6)} {c['unit']}, error {c['error_percent']:+.4f}% (tolerance {c['tolerance_percent']}%)")
        lines.append("")
    s = json.loads((DATA / "sweeps.json").read_text())
    lines += ["## Sweeps", "", "Padeye (2 points, S355): angle, load t, mass kg, sling t, shackle t, plate mm, cheeks, governing, use"]
    for p in s["padeye"]:
        lines.append(f"- {p['angle']} deg, {p['load_t']} t: " + (f"{p['mass_kg']:.3f} kg, sling {p['sling_t']:.2f} t, shackle {p['shackle_t']} t, plate {p['plate_mm']}, cheeks {p['cheeks']}, {p['governing']} {p['use']*100:.0f}%" if p["mass_kg"] else p.get("reason", "")))
    lines += ["", "Bracket vs pipe size (3 m span, seawater):"]
    for p in s["bracket"]:
        lines.append(f"- NPS {p['nps']} (OD {p['od_mm']}): down {p['down_kn']:.2f} kN, mass {p['mass_kg']}, governing {p['governing']} {p['use']}, fn {p['natural_hz']:.1f} Hz, recommended {p['recommended_m']} m, spans {p['spans_m']}")
    lines += ["", "Pipe span vs spacing (NPS 4):"]
    for p in s["bracket_span"]:
        lines.append(f"- {p['span_m']} m: fn {p['natural_hz']:.2f} Hz, separation {p['separation']*100:.1f}% from {p['nearest']}, pipe stress {p['pipe_stress_mpa']:.1f} MPa")
    lines += ["", "Fin vs speed (1.4 x 1.2 m, NACA 0020, 22 deg):"]
    for p in s["fin"]:
        lines.append(f"- {p['speed_kn']} kn: lift {p['nemo_lift_kn']:.1f} kN, UR S10 {p['ur_s10_kn']:.1f} kN, design {p['design_kn']:.1f} kN, torque {p['torque_knm']:.2f} kNm, "
                     f"cp_min {p['cp_min']:.2f}, sigma {p['sigma']:.2f}, mass {p['mass_kg']}, stock {p['stock_mm']}, governing {p['governing']}")
    (DATA / "facts.md").write_text("\n".join(lines), encoding="utf-8")
    print(len(lines), "lines")


if __name__ == "__main__":
    main()
